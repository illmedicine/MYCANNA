// Build reverse map: region → which CONDITION_INSIGHTS keys belong there
export function getConditionsForRegion(regionId, activeConditions) {
  return activeConditions
    .filter(name => CONDITION_REGION_MAP[name] === regionId && CONDITION_INSIGHTS[name])
    .map(name => ({ name, ...CONDITION_INSIGHTS[name] }));
}

// Return set of region IDs that have at least one active user condition
export function getActiveConditionRegions(activeConditions) {
  const regions = new Set();
  activeConditions.forEach(name => {
    const r = CONDITION_REGION_MAP[name];
    if (r) regions.add(r);
  });
  return regions;
}
